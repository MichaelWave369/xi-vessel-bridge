#!/usr/bin/env node
"use strict";
/** R18.9 PHI-authored ASCII JSON subset, not JCS or an Xi-approved wire format.
 * Uses only local Node standard library. No sockets, signatures or execution.
 */
const fs=require("node:fs");
const crypto=require("node:crypto");
const SCHEMA="PhiXi.R18_9_PublicIllustrativeReceipt.v1";
const PROFILE="PhiXi.R18_9.ASCII_SORTED_JSON.v1";
const CHECK_SCHEMA="PhiXi.R18_9_CanonicalReceiptCheck.v1";
const CASES=Object.freeze({
 digest:"SYNTHETIC_DIGEST_REVIEW_ONLY",
 policy:"SYNTHETIC_POLICY_DENIAL_REVIEW_ONLY",
 replay:"SYNTHETIC_REPLAY_DENIAL_REVIEW_ONLY",
 revoked:"SYNTHETIC_REVOCATION_REVIEW_ONLY"
});
const FIXTURE=Buffer.from(
 "PHI-XI R18 SYNTHETIC DIGEST FIXTURE v1\n"+
 "NO PRIVATE DATA; NO AUTHORITY; NO REMOTE RIGHTS.\n","ascii");
const FIXTURE_SHA="8370bdb1f706a2168accc1c225a37c98ec907cd3e954b67c1cdcc9d8ddd8feb5";
const MAX_BYTES=4096;
function sha(bytes){return crypto.createHash("sha256").update(bytes).digest("hex");}
function requireThat(ok,reason){if(!ok)throw Error(reason);}
function _canonical(value){
 if(typeof value==="string"){
  requireThat(/^[\x20-\x7e]*$/.test(value),"non-ASCII string");
  // JSON.stringify escapes ASCII control characters and quotes consistently.
  return JSON.stringify(value);
 }
 if(typeof value==="boolean")return value?"true":"false";
 if(typeof value==="number"){
  requireThat(Number.isSafeInteger(value)&&value>=0,"unsafe integer");
  return JSON.stringify(value);
 }
 if(Array.isArray(value))return "["+value.map(_canonical).join(",")+"]";
 requireThat(value!==null&&typeof value==="object"&&
  Object.getPrototypeOf(value)===Object.prototype,"unsupported value");
 const keys=Object.keys(value).sort();
 requireThat(keys.every(k=>/^[\x20-\x7e]*$/.test(k)),"non-ASCII object key");
 return "{"+keys.map(k=>JSON.stringify(k)+":"+_canonical(value[k])).join(",")+"}";
}
function canonical(value){
 const b=Buffer.from(_canonical(value)+"\n","ascii");
 requireThat(b.length<=MAX_BYTES,"oversized canonical receipt");
 return b;
}
function make(id){
 requireThat(Object.prototype.hasOwnProperty.call(CASES,id),"unknown candidate case");
 requireThat(FIXTURE.length===88&&sha(FIXTURE)===FIXTURE_SHA,"fixture bytes changed");
 return {
  schema:SCHEMA,canonical_profile:PROFILE,case_id:id,review_label:CASES[id],
  subject:{origin:"PHI369-local-synthetic-fixture",classification:"synthetic_public",
   operation:"artifact.sha256",bytes:FIXTURE.length,sha256:sha(FIXTURE)},
  parties:["phi-sim","xi-sim"],
  example_only:true,observed_exchange:false,
  independent_signatures_verified:0,operator_approvals:0,approved_operations:0,
  r17_external_pilot:"BLOCKED",r18_real_two_host_pilot:"NOT_RUN",
  live_xi_connected:false,authority:"none"
 };
}
function emit(id){return canonical(make(id));}
function verify(data){
 requireThat(Buffer.isBuffer(data)&&data.length>0&&data.length<=MAX_BYTES,"invalid input size");
 // Exact original bytes MUST match independently generated bytes. JSON.parse
 // alone accepts duplicate keys, but duplicated raw keys necessarily mismatch.
 const string=data.toString("utf8");
 requireThat(Buffer.from(string,"utf8").equals(data),"not valid UTF-8");
 const parsed=JSON.parse(string);
 requireThat(parsed&&typeof parsed==="object"&&!Array.isArray(parsed),"not an object");
 const id=parsed.case_id;
 requireThat(typeof id==="string"&&Object.prototype.hasOwnProperty.call(CASES,id),
  "unrecognized case");
 requireThat(data.equals(emit(id)),"noncanonical or forged receipt bytes");
 return {
  schema:CHECK_SCHEMA,status:"CANONICAL_BYTES_MATCH_UNAUTHENTICATED",
  case_id:id,sha256:sha(data),canonical_bytes:data.length,
  independent_signatures_verified:0,approved_operations:0,
  live_xi_connected:false,authority:"none"
 };
}
function main(args){
 if(args.length===1&&args[0]==="require-live"){
  process.stdout.write('{"status":"LIVE_AUTHORITY_REFUSED","authority":"none"}\n');
  return 2;
 }
 const [cmd,flag,value,...remaining]=args;
 if(cmd==="emit"&&flag==="--case"&&
   (remaining.length===0||(remaining.length===2&&remaining[0]==="--out"))){
  const raw=emit(value);
  if(remaining.length)fs.writeFileSync(remaining[1],raw,{flag:"w"});
  else process.stdout.write(raw);
  return 0;
 }
 if(cmd==="verify"&&flag==="--file"&&typeof value==="string"&&remaining.length===0){
  const info=fs.statSync(value);
  requireThat(info.isFile()&&info.size<=MAX_BYTES&&!info.isSymbolicLink(),"invalid file");
  process.stdout.write(JSON.stringify(verify(fs.readFileSync(value)))+"\n");
  return 0;
 }
 throw Error("usage: emit --case digest|policy|replay|revoked [--out FILE] | verify --file FILE | require-live");
}
if(require.main===module){
 try{process.exitCode=main(process.argv.slice(2));}
 catch(_){process.stderr.write('{"status":"CANONICAL_RECEIPT_REFUSED","authority":"none","live_xi_connected":false}\n');process.exitCode=2;}
}
module.exports={SCHEMA,PROFILE,CASES,FIXTURE_SHA,canonical,make,emit,verify,main};
